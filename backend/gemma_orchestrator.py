class GemmaInterventionNarrative(BaseModel):
    technique_id: TechniqueId
    rationale: str = Field(min_length=1, max_length=1600)
    implementation_steps: list[str] = Field(min_length=3, max_length=6)
    caveats: list[str] = Field(min_length=1, max_length=6)


class GemmaRecommendation(BaseModel):
    """Frontend-compatible structured recommendation generated by Gemma 4."""

    alert_level: Literal["LOW", "MODERATE", "HIGH", "CRITICAL"]
    coral_health_summary: str = Field(min_length=1, max_length=600)
    environmental_assessment: str = Field(min_length=1, max_length=1000)
    recommended_technique: TechniqueId
    technique_name: str = Field(min_length=1, max_length=300)
    reasoning: str = Field(min_length=1, max_length=3000)
    predicted_survival_rate: str = Field(min_length=1, max_length=30)
    estimated_cost_per_hectare: str = Field(min_length=1, max_length=50)
    risk_factors: list[str] = Field(min_length=1, max_length=12)
    next_steps: list[str] = Field(min_length=1, max_length=12)
    confidence_score: float = Field(ge=0.0, le=1.0)
    interventions: list[GemmaInterventionNarrative] = Field(
        min_length=3,
        max_length=5,
    )


